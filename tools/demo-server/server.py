def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def initials(name):
    digits = {"One": "1", "Two": "2"}
    words = [digits.get(w, w) for w in re.split(r"[^A-Za-z0-9]+", name) if w]
    return (words[0][:2] if len(words) == 1 else "".join(w[0] for w in words[:3])).upper()


