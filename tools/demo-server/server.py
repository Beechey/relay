def xmltv(base, now):
    t = lambda s: datetime.fromtimestamp(s, timezone.utc).strftime("%Y%m%d%H%M%S +0000")
    out = ['<?xml version="1.0" encoding="UTF-8"?>\n<tv generator-info-name="relay-demo-server">']
    for c in CHANNELS:
        out.append(f'<channel id="{c["slug"]}.demo"><display-name>{escape(c["name"])}</display-name>'
                   f'<icon src="{base}/media/logos/{c["slug"]}.png"/></channel>')
    for c in CHANNELS:
        for a, b, title, desc in schedule(c, now):
            if b > now - 2 * 3600:
                out.append(f'<programme start="{t(a)}" stop="{t(b)}" channel="{c["slug"]}.demo">'
                           f'<title lang="en">{escape(title)}</title><desc lang="en">{escape(desc)}</desc></programme>')
    out.append("</tv>")
    return "\n".join(out).encode()


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def do_GET(self):
        url = urlparse(self.path)
        q = {k: v[0] for k, v in parse_qs(url.query).items()}
        base = f"http://{self.headers.get('Host', 'localhost')}"
        now = int(time.time())
        path = url.path
        if path == "/player_api.php":
            return self.send(200, "application/json", json.dumps(player_api(q, base, now)).encode())
        if path == "/xmltv.php":
            if q.get("username") != USER or q.get("password") != PASS:
                return self.send(401, "text/plain", b"unauthorised")
            return self.send(200, "application/xml", xmltv(base, now))
        if path.startswith("/media/"):
            return self.file(os.path.normpath(os.path.join(MEDIA, path[len("/media/"):])))
        m = re.fullmatch(r"/(live|movie|series|timeshift)/([^/]+)/([^/]+)/(?:.*/)?(\d+)\.(\w+)", path)
        if m and m[2] == USER and m[3] == PASS:
            if m[5] == "m3u8":  # one long segment is enough for a demo
                return self.send(200, "application/vnd.apple.mpegurl",
                                 b"#EXTM3U\n#EXT-X-VERSION:3\n#EXT-X-TARGETDURATION:180\n#EXT-X-PLAYLIST-TYPE:VOD\n"
                                 b"#EXTINF:180.0,\n/media/clip.ts\n#EXT-X-ENDLIST\n")
            return self.file(os.path.join(MEDIA, "clip.ts" if m[1] in ("live", "timeshift") else "clip.mp4"))
        self.send(404, "text/plain", b"not found")

    def send(self, code, ctype, body, headers=()):
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        for k, v in headers:
            self.send_header(k, v)
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(body)

    def file(self, fs_path):
        if not fs_path.startswith(MEDIA + os.sep) or not os.path.isfile(fs_path):
            return self.send(404, "text/plain", b"not found (did you make media/clip.mp4 and clip.ts? see README)")
        ctype = {".jpg": "image/jpeg", ".png": "image/png", ".mp4": "video/mp4", ".ts": "video/mp2t"}.get(
            os.path.splitext(fs_path)[1], "application/octet-stream")
        size = os.path.getsize(fs_path)
        start, end = 0, size - 1
        r = re.fullmatch(r"bytes=(\d*)-(\d*)", self.headers.get("Range", ""))
        if r and (r[1] or r[2]):
            start, end = (int(r[1]), int(r[2]) if r[2] else size - 1) if r[1] else (size - int(r[2]), size - 1)
            if start >= size or start > end:
                return self.send(416, "text/plain", b"", [("Content-Range", f"bytes */{size}")])
            end = min(end, size - 1)
        self.send_response(206 if r and (r[1] or r[2]) else 200)
        self.send_header("Content-Type", ctype)
        self.send_header("Accept-Ranges", "bytes")
        self.send_header("Content-Length", str(end - start + 1))
        if r and (r[1] or r[2]):
            self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
        self.end_headers()
        if self.command == "HEAD":
            return
        with open(fs_path, "rb") as f:
            f.seek(start)
            left = end - start + 1
            try:
                while left > 0:
                    chunk = f.read(min(65536, left))
                    if not chunk:
                        break
                    self.wfile.write(chunk)
                    left -= len(chunk)
            except (BrokenPipeError, ConnectionResetError):
                pass  # players drop connections when they seek or stop

    do_HEAD = do_GET


