def schedule(ch, now):
    """Deterministic programmes for one channel from yesterday 00:00 UTC to now + 26 h."""
    day = now - now % 86400
    t, end, rng, out = day - 86400, now + 26 * 3600, random.Random(ch["id"]), []
    while t < end:
        title, desc, minutes = rng.choice([p for p in ch["pool"] if not out or p[0] != out[-1][2]])
        length = max(minutes, 30) if minutes < 30 and rng.random() < 0.5 else minutes
        out.append((t, t + length * 60, title, desc))
        t += length * 60
    return out


